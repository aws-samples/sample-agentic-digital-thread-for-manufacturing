"""Capture a deployment's harness env into a sourceable, gitignored file.

Reads the *same* CloudFormation outputs and Secrets Manager secret that
``deploy.sh`` resolves via its ``cfn_output()`` helper, then writes a
``chmod 600`` ``tests/harness/.harness-env`` you can ``source`` to populate the
environment the rest of the harness (and ``agents.db``) expects:

    GRAPH_IDENTIFIER  <- ADTDatabaseStack.NeptuneGraphId   (cfn output)
    ADT_BASE_URL       <- ADTComputeStack.ADTCloudFrontUrl   (cfn output)
    ADT_USERNAME       <- the demo Cognito username (default ``ADT``)
    ADT_PASSWORD       <- Secrets Manager secret 'adt-demo-password'
    AWS_REGION        <- the resolved region
    AWS_PROFILE       <- the resolved profile (if any)

Credentials are taken from the ambient SSO/profile/env chain via boto3 — this
script never hardcodes secrets, and the demo password is NEVER printed to
stdout (it is referenced by name only). Run it from ``agentic_digital_thread/``::

    python -m tests.harness.capture_env --profile <p> --region us-east-1
"""

from __future__ import annotations

import argparse
import os
import shlex
import sys
from pathlib import Path

import boto3

# Mirror deploy.sh: GRAPH_IDENTIFIER=ADTDatabaseStack.NeptuneGraphId,
# ADT_BASE_URL=ADTComputeStack.ADTCloudFrontUrl, ADT_PASSWORD=secret adt-demo-password.
GRAPH_STACK, GRAPH_OUTPUT = "ADTDatabaseStack", "NeptuneGraphId"
BASE_URL_STACK, BASE_URL_OUTPUT = "ADTComputeStack", "ADTCloudFrontUrl"
PASSWORD_SECRET_ID = "adt-demo-password"  # nosec B105 - not a credential: field/env/secret NAME, sentinel, or offline test fixture
# The demo Cognito username (same default as tests/e2e/conftest.py and
# tests/harness/graph_reset.py) — exported so `source .harness-env` alone is
# enough for the e2e suite; override via the ambient ADT_USERNAME.
DEFAULT_USERNAME = "ADT"

ENV_FILE = Path(__file__).resolve().parent / ".harness-env"


def cfn_output(session: boto3.Session, region: str, stack: str, key: str) -> str:
    """Return a single CloudFormation stack output value (mirrors deploy.sh cfn_output())."""
    cfn = session.client("cloudformation", region_name=region)
    stacks = cfn.describe_stacks(StackName=stack)["Stacks"]
    for output in stacks[0].get("Outputs", []):
        if output.get("OutputKey") == key:
            return output.get("OutputValue", "")
    return ""


def get_secret(session: boto3.Session, region: str, secret_id: str) -> str:
    """Return a Secrets Manager secret string (the demo password)."""
    sm = session.client("secretsmanager", region_name=region)
    return sm.get_secret_value(SecretId=secret_id)["SecretString"]


def write_env_file(values: dict[str, str]) -> None:
    """Write a sourceable, chmod-600 .harness-env (created 0600 from the start)."""
    lines = [
        "# Auto-generated by tests.harness.capture_env — DO NOT COMMIT.",
        "# Source this file: `source tests/harness/.harness-env`",
    ]
    lines += [f"export {name}={shlex.quote(value)}" for name, value in values.items()]
    body = "\n".join(lines) + "\n"
    # Create with 0600 atomically so the secret is never briefly world-readable.
    fd = os.open(str(ENV_FILE), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(body)
    os.chmod(ENV_FILE, 0o600)


def capture(profile: str | None, region: str) -> dict[str, str]:
    """Resolve the three deploy.sh outputs and assemble the env var mapping."""
    session = boto3.Session(profile_name=profile) if profile else boto3.Session()
    values = {
        "GRAPH_IDENTIFIER": cfn_output(session, region, GRAPH_STACK, GRAPH_OUTPUT),
        "AWS_REGION": region,
        "ADT_BASE_URL": cfn_output(session, region, BASE_URL_STACK, BASE_URL_OUTPUT),
        "ADT_USERNAME": os.environ.get("ADT_USERNAME", DEFAULT_USERNAME),
        "ADT_PASSWORD": get_secret(session, region, PASSWORD_SECRET_ID),
        "AWS_PROFILE": profile or os.environ.get("AWS_PROFILE", ""),
    }
    return values


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m tests.harness.capture_env",
        description="Capture deployment outputs into tests/harness/.harness-env (chmod 600).",
    )
    parser.add_argument("--profile", default=None, help="AWS profile (default: ambient creds).")
    parser.add_argument("--region", default=os.environ.get("AWS_REGION", "us-east-1"),
                        help="AWS region (default: AWS_REGION or us-east-1).")
    args = parser.parse_args(argv)

    try:
        values = capture(args.profile, args.region)
    except Exception as exc:  # noqa: BLE001 — surface any AWS/cred error clearly, no traceback
        print(f"ERROR: failed to capture harness env: {exc}", file=sys.stderr)
        return 1

    missing = [k for k in ("GRAPH_IDENTIFIER", "ADT_BASE_URL", "ADT_PASSWORD") if not values.get(k)]
    if missing:
        print(f"ERROR: empty required value(s): {', '.join(missing)} "
              f"(is the deployment up in {args.region}?)", file=sys.stderr)
        return 1

    write_env_file(values)
    # Print confirmation WITHOUT the secret — ADT_PASSWORD is referenced by name only.
    print(f"Wrote {ENV_FILE} (chmod 600). Source it: source {ENV_FILE}")
    print(f"  GRAPH_IDENTIFIER = {values['GRAPH_IDENTIFIER']}")
    print(f"  AWS_REGION       = {values['AWS_REGION']}")
    print(f"  ADT_BASE_URL      = {values['ADT_BASE_URL']}")
    print(f"  ADT_USERNAME      = {values['ADT_USERNAME']}")
    print(f"  AWS_PROFILE      = {values['AWS_PROFILE'] or '(ambient)'}")
    print("  ADT_PASSWORD      = (captured from Secrets Manager — not shown)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
