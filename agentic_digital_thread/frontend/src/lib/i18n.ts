/** UI language for a selection — dictionary languages only, else 'en'
 * (legacy _i18nUiLang guard). */
function uiLangOf(lang: string): string {
  return Object.prototype.hasOwnProperty.call(I18N, lang) ? lang : 'en';
}

/** Persisted response language, safe against environments without
 * localStorage/navigator (node-env tests import this module transitively). */
function persistedLang(): string {
  try {
    return getResponseLang();
  } catch {
    return 'en';
  }
}

/** Current-language store — initialized from the SAME persistence the legacy
 * uses ('adt-lang' via getResponseLang). Holds the raw selection; t()/uiLangOf
 * apply the dictionary guard. */
export const langStore: Store<string> = createStore<string>(persistedLang());

/** Mirror of the legacy applyI18n() side effect: keep <html lang> in step. */
function syncDocLang(): void {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = uiLangOf(langStore.get());
  }
}

/** Change the UI + AI-response language: persists 'adt-lang' (i18n-lang.ts,
 * same key as the static fallback) and notifies useI18n subscribers — the
 * React replacement for legacy setResponseLang→applyI18n. */
export function setLang(lang: string): void {
  setResponseLang(lang);
  langStore.set(lang);
  syncDocLang();
}

/** Translate a key for the current language. Missing keys fall back to the
 * English value, then to the key itself — NEVER blank (legacy t()). */
export function t(key: string): string {
  return I18N[uiLangOf(langStore.get())]?.[key] ?? I18N.en?.[key] ?? key;
}

/** t() plus `{name}` placeholder substitution. Values are inserted as plain
 * text (callers render the result as a React text node, never HTML); a
 * placeholder with no value is left as-is so a missing variable is visible
 * instead of silently blank. */
export function tf(key: string, vars: Record<string, string | number>): string {
  return t(key).replace(/\{(\w+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole,
  );
}

/** Subscribe a component to the current language. Returns the (stable) t —
 * the store subscription is what triggers the re-render on setLang. */
export function useI18n(): { lang: string; t: typeof t } {
  const lang = useStore(langStore);
  return { lang, t };
}

