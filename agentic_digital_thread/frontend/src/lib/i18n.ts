/* i18n — UI chrome translation (dictionary-driven).
 *
 * Translates the app chrome (nav, header menu, chat affordances, dashboard
 * section headers, common buttons) keyed off the same language selection as
 * the AI-response directive (lib/i18n-lang.ts, localStorage 'adt-lang') — so
 * the SPA and the static fallback always agree on the persisted language.
 *
 * React idiom replaces the legacy DOM-walking applyI18n(): the current
 * language lives in a `createStore` slice; components subscribe through
 * useI18n() and render t(key) directly — no data-i18n attributes, no
 * post-render text swapping. Missing keys fall back to English, then to the
 * key itself — NEVER blank. The `en` dictionary values are byte-identical to
 * the shipped English markup, so lang=en renders exactly today's UI.
 *
 * Scope is deliberately pragmatic (chrome i18n, not full-app i18n): the
 * dictionaries carry keys for strings rendered by other modules
 * (dash.*, arch.*, onboard.*, chat.*, memory.*, sl.*) so those components can
 * adopt t(key) later without a dictionary change. The DICTIONARY OBJECT BELOW
 * is the single source of truth (originally ported verbatim from the legacy
 * static UI, removed 2026-07-31) — structural contract pinned by
 * src/test/i18n-chrome.test.tsx.
 */
