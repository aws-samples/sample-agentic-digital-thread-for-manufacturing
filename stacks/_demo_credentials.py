"""
Demo credentials for the Agentic Digital Thread sample.

⚠️ SECURITY NOTE ⚠️

No hardcoded passwords in source. The demo password is set ONCE at the first
deploy and is STABLE across subsequent deploys (it does not rotate). It is
either:

1. Provided at deploy time: cdk deploy -c demo_password='<your-password>'
   ⚠️ CAVEAT: an explicit override is embedded in PLAIN TEXT in the synthesized
   CloudFormation template (SecretValue.unsafe_plain_text below) — visible in
   cdk.out/, the CloudFormation console, and DescribeStacks/GetTemplate API
   calls. For anything sensitive, prefer option 2 (the generated-password path).
2. Auto-generated by CloudFormation and stored in Secrets Manager. Because the
   value is generated by CloudFormation (GenerateSecretString) and preserved
   across stack updates, redeploys do NOT rotate it. Retrieve post-deploy:

    aws secretsmanager get-secret-value --secret-id adt-demo-password \\
        --query SecretString --output text

The password is used for initial access to demo dashboards (HighByte, ADT app,
ERP Dashboard). For production use, always provide a strong custom password.
"""

import hashlib
from typing import Optional

import aws_cdk as cdk
from aws_cdk import aws_secretsmanager as secretsmanager, RemovalPolicy, SecretValue
from constructs import Construct, IConstruct

# Stable, non-secret token returned by get_demo_password() when no explicit
# override is supplied. It is used ONLY as a CloudFormation change-trigger
# (custom-resource "PasswordTrigger" property) so the password-setting custom
# resources do NOT re-run on every deploy. It is never used as a real password:
# when no override is set the actual password is generated by CloudFormation
# (see create_demo_password_secret) and read from Secrets Manager at runtime.
_STABLE_TRIGGER_TOKEN = "cfn-generated"  # nosec B105 - sentinel trigger string, not a credential


def _password_override(app_or_construct: cdk.App | IConstruct) -> Optional[str]:
    """Return an explicit password override from context, or None.

    Priority:
    1. -c demo_password=<value> (explicit override)
    2. -c highbyte_password=<value> (legacy compat)
    """
    override: Optional[str] = app_or_construct.node.try_get_context("demo_password")
    if override:
        return override
    legacy: Optional[str] = app_or_construct.node.try_get_context("highbyte_password")
    if legacy:
        return legacy
    return None


def get_demo_password(app_or_construct: cdk.App | IConstruct) -> str:
    """Return a STABLE change-trigger value for the demo password.

    This function is used by the password-setting custom resources as a
    CloudFormation "PasswordTrigger" property — it forces those resources to
    re-run only when the value changes. It NEVER returns the password itself:
    the property lands in three synthesized templates and in the custom
    resource's invocation event (CloudTrail / Lambda logs), so the override is
    reduced to a truncated SHA-256 digest — it still changes exactly when the
    password changes, and reveals nothing.

    Priority:
    1. -c demo_password=<value> (explicit override) — digest of the value.
    2. -c highbyte_password=<value> (legacy compat) — digest of the value.
    3. A stable constant token (NOT a real password and NOT a fresh random each
       synth) so redeploys do not rotate the secret or the demo users.

    When no override is set the actual password is generated ONCE by
    CloudFormation in create_demo_password_secret() and read from Secrets
    Manager at runtime; this function only supplies the change-trigger.
    """
    override = _password_override(app_or_construct)
    if override:
        return password_trigger_digest(override)
    return _STABLE_TRIGGER_TOKEN


def password_trigger_digest(value: str) -> str:
    """The change-trigger for an explicit override: ``sha256:<16 hex>``."""
    return "sha256:" + hashlib.sha256(value.encode("utf-8")).hexdigest()[:16]


def create_demo_password_secret(scope: Construct) -> secretsmanager.Secret:
    """Create the Secrets Manager secret storing the demo password.

    Behaviour:
    - With an explicit override (-c demo_password / -c highbyte_password): the
      secret stores that literal value.
    - Without an override: CloudFormation generates the password ONCE at create
      time (GenerateSecretString) and PRESERVES it across stack updates, so
      redeploys do not rotate it.

    The secret name and removal policy are stable so all consumers can resolve
    it by name (adt-demo-password) and it is cleaned up on teardown.
    """
    override = _password_override(scope)
    if override:
        # NOTE: unsafe_plain_text embeds the override value in plain text in the
        # synthesized CloudFormation template (cdk.out/, CloudFormation console,
        # DescribeStacks/GetTemplate). Acceptable for a throwaway demo password;
        # for anything sensitive use the generated-password path below instead.
        return secretsmanager.Secret(
            scope, "DemoPasswordSecret",
            secret_name="adt-demo-password",  # nosec B106 - Secrets Manager construct name, not credential value
            description="ADT demo password. Retrieve: aws secretsmanager get-secret-value --secret-id adt-demo-password --query SecretString --output text",
            secret_string_value=SecretValue.unsafe_plain_text(override),
            removal_policy=RemovalPolicy.DESTROY,
        )

    # No override: let CloudFormation generate the value once and keep it stable
    # across updates. exclude_punctuation keeps the password broadly compatible
    # with the demo dashboards (matches the previous letters+digits character
    # set); include_space=False avoids whitespace in copy/paste.
    return secretsmanager.Secret(
        scope, "DemoPasswordSecret",
        secret_name="adt-demo-password",  # nosec B106 - Secrets Manager construct name, not credential value
        description="ADT demo password. Retrieve: aws secretsmanager get-secret-value --secret-id adt-demo-password --query SecretString --output text",
        generate_secret_string=secretsmanager.SecretStringGenerator(
            password_length=16,
            exclude_punctuation=True,
            include_space=False,
        ),
        removal_policy=RemovalPolicy.DESTROY,
    )
