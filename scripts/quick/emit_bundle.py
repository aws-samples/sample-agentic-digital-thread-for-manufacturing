# Every token the template must carry; build_bundle() asserts each is present
# and that every one is consumed during the single-pass render.
_TOKENS = (
    "__ADT_MCP_URL__",
    "__ADT_TOKEN_URL__",
    "__ADT_CLIENT_ID__",
    "__ADT_SCOPE__",
    "__ADT_MODE__",
    "__ADT_PROFILE_TAG__",
    "__ADT_KEYCHAIN_SERVICE__",
    "__ADT_INSTRUCTIONS_TOOL__",
    "__ADT_REFRESH_THRESHOLD_SECONDS__",
    "__ADT_PROMPT_SNAPSHOT_B64__",
    "__ADT_SKILL_TEMPLATE_B64__",
    "__ADT_EMBEDDED_SECRET_B64__",
)

# Single-pass token matcher: replacement happens in ONE re.sub pass, so a
# substituted VALUE can never itself be treated as a token (no re-scan).
_TOKEN_RE = re.compile(r"__ADT_[A-Z0-9_]+__")

# Strict allowlists for the raw scalar values baked into the bundle's shell
# single-quoted assignments. Anything outside these shapes (quotes, spaces,
# `$(...)`, backticks, semicolons, …) is rejected — emit-time template
# injection is not a thing we sanitize, we refuse it.
_URL_RE = re.compile(r"^https://[A-Za-z0-9._/-]+$")
_SCALAR_ALLOWLIST: dict[str, re.Pattern] = {
    "mcp_url": _URL_RE,
    "token_url": _URL_RE,
    "client_id": re.compile(r"^[A-Za-z0-9]+$"),
    "scope": re.compile(r"^[A-Za-z0-9/_.:-]+$"),
    "profile_tag": re.compile(r"^[A-Za-z0-9._-]+$"),
}


def _b64(text: str) -> str:
    return base64.b64encode(text.encode("utf-8")).decode("ascii")


def _validate_scalars(scalars: dict[str, str]) -> None:
    """Refuse any baked scalar outside its strict allowlist (F2) — ValueError
    names the offending field."""
    for field, pattern in _SCALAR_ALLOWLIST.items():
        if not pattern.fullmatch(scalars[field]):
            raise ValueError(
                f"{field} value fails the strict allowlist ({pattern.pattern}) "
                "— refusing to render the bundle"
            )


def _render_template(replacements: dict[str, str]) -> str:
    """Single-pass re.sub render: a substituted value that happens to contain
    a ``__ADT_*__`` token string is inert text, never re-expanded. Asserts
    every replacement token exists in the template AND is consumed."""
    for token in _TOKENS:
        if token not in BUNDLE_TEMPLATE:
            raise AssertionError(f"template drift: token {token} missing")
    consumed: set[str] = set()

    def _substitute(match: re.Match) -> str:
        token = match.group(0)
        if token not in replacements:
            raise AssertionError(f"template drift: unknown token {token} in template")
        consumed.add(token)
        return replacements[token]

    rendered = _TOKEN_RE.sub(_substitute, BUNDLE_TEMPLATE)
    unconsumed = set(replacements) - consumed
    if unconsumed:
        raise AssertionError(
            f"template drift: tokens never rendered: {sorted(unconsumed)}"
        )
    return rendered


def build_bundle(
    *,
    mcp_url: str,
    token_url: str,
    client_id: str,
    scope: str,
    mode: str,
    profile_tag: str,
    prompt_text: str,
    skill_template: str,
    embedded_secret: str | None = None,
) -> str:
    """Render the bundle from the module-level template. Pure function — no
    I/O, no AWS access — so it is directly unit-testable.

    The five caller-supplied scalars are allowlist-validated (ValueError names
    the offending field) and substitution is a SINGLE re.sub pass, so a
    substituted value that happens to contain a ``__ADT_*__`` token string is
    inert text, never re-expanded."""
    if mode not in ("agent", "orchestrator"):
        raise ValueError(f"mode must be 'agent' or 'orchestrator', got {mode!r}")
    _validate_scalars({
        "mcp_url": mcp_url,
        "token_url": token_url,
        "client_id": client_id,
        "scope": scope,
        "profile_tag": profile_tag,
    })
    return _render_template({
        "__ADT_MCP_URL__": mcp_url,
        "__ADT_TOKEN_URL__": token_url,
        "__ADT_CLIENT_ID__": client_id,
        "__ADT_SCOPE__": scope,
        "__ADT_MODE__": mode,
        "__ADT_PROFILE_TAG__": profile_tag,
        "__ADT_KEYCHAIN_SERVICE__": KEYCHAIN_SERVICE,
        "__ADT_INSTRUCTIONS_TOOL__": INSTRUCTIONS_TOOL,
        "__ADT_REFRESH_THRESHOLD_SECONDS__": str(REFRESH_THRESHOLD_SECONDS),
        "__ADT_PROMPT_SNAPSHOT_B64__": _b64(prompt_text),
        "__ADT_SKILL_TEMPLATE_B64__": _b64(skill_template),
        "__ADT_EMBEDDED_SECRET_B64__": _b64(embedded_secret) if embedded_secret else "",
    })


def _build_parser() -> argparse.ArgumentParser:
    """Argument parsing, factored out of main() (pure decomposition)."""
    parser = argparse.ArgumentParser(
        description="Emit a self-contained ADT Quick Desktop installer bundle "
        "(bash + curl + python3 only; no repo, no AWS CLI)."
    )
    parser.add_argument("--out", required=True, help="output bundle path")
    parser.add_argument("--mcp-url", required=True, help="gateway MCP endpoint URL")
    parser.add_argument("--token-url", required=True, help="Cognito OAuth2 token URL")
    parser.add_argument("--client-id", required=True, help="M2M client id")
    parser.add_argument("--scope", required=True, help="OAuth scope (e.g. adt/query)")
    parser.add_argument(
        "--mode", required=True, choices=("agent", "orchestrator"),
        help="baked query-mode fallback used when live detection fails",
    )
    parser.add_argument(
        "--prompt-file", required=True,
        help="emit-time Quick system prompt snapshot (bundle fallback payload)",
    )
    parser.add_argument(
        "--skill-file", required=True,
        help="SKILL.md template (frontmatter head is reused verbatim)",
    )
    parser.add_argument(
        "--profile-tag", required=True,
        help="emitting AWS profile tag — keys the adt-quick-m2m Keychain account "
        "and the mcp_config entry name",
    )
    parser.add_argument(
        "--embed-secret", action="store_true",
        help="embed the client secret read from the ADT_EMBED_SECRET environment "
        "variable (NEVER passed via argv). DANGEROUS: the output file then "
        "contains a live credential.",
    )
    return parser


def _resolve_embedded_secret(
    parser: argparse.ArgumentParser, args: argparse.Namespace
) -> str | None:
    """Read the opt-in embedded secret from the environment (never argv) and
    print the loud warning. Returns None when --embed-secret was not passed."""
    if not args.embed_secret:
        return None
    embedded_secret = os.environ.get("ADT_EMBED_SECRET", "")
    if not embedded_secret:
        parser.error("--embed-secret requires the ADT_EMBED_SECRET environment variable")
    print(EMBED_WARNING_BANNER, file=sys.stderr)
    return embedded_secret


def _render_bundle_from_args(
    args: argparse.Namespace, embedded_secret: str | None
) -> str:
    """Read the payload files and render the bundle text (template rendering)."""
    return build_bundle(
        mcp_url=args.mcp_url,
        token_url=args.token_url,
        client_id=args.client_id,
        scope=args.scope,
        mode=args.mode,
        profile_tag=args.profile_tag,
        prompt_text=Path(args.prompt_file).read_text(encoding="utf-8"),
        skill_template=Path(args.skill_file).read_text(encoding="utf-8"),
        embedded_secret=embedded_secret,
    )


def _write_bundle(out: Path, bundle: str, *, secret_embedded: bool = False) -> None:
    """Write the rendered bundle executable.

    Mode 0700 (owner-only) when a live credential is embedded — anyone who can
    read the file can mint gateway tokens — else the shareable 0755."""
    mode = 0o700 if secret_embedded else 0o755
    out.write_text(bundle, encoding="utf-8")
    out.chmod(mode)
    print(f"==> portable bundle written → {out} (mode {mode:04o})")


def main(argv: list[str] | None = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)
    embedded_secret = _resolve_embedded_secret(parser, args)
    bundle = _render_bundle_from_args(args, embedded_secret)
    _write_bundle(Path(args.out), bundle, secret_embedded=embedded_secret is not None)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
